function trx(rows: TrxRow[]): Exercise[] {
  return rows.map(([id, name, muscle, pose, s1, s2, s3]) => ({
    id,
    name,
    equipment: 'trx',
    muscle,
    pose,
    gear: { trx: true },
    sets: 3,
    reps: '10–12',
    rest: 60,
    trx: true,
    steps: [s1, s2, s3],
    mistake: 'Dejar que la correa pierda tensión en la mitad del recorrido.',
    breathing: 'Suelta el aire en la parte más dura del movimiento.',
  }))
}

